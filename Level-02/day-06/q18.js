// Write a program to read the marks of a student & print the grade (A/B/C/D/Fail).

let marks = 90;

if (marks >= 80) {
    console.log("A");
} else if (marks >= 70) {
    console.log("B");
} else if (marks >= 60) {
    console.log("C");
} else if (marks >= 50) {
    console.log("D");
} else {
    console.log("Fail");
}